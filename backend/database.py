import os
import sqlite3
from contextlib import contextmanager
from datetime import date, datetime, timezone

import psycopg

DEFAULT_SQLITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "budgetbuddy.db")


class DuplicateEmail(Exception):
    pass


def _now():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class Database:
    def __init__(self, url=None):
        self.url = url or os.getenv("DATABASE_URL")
        if self.url and self.url.startswith(("postgres://", "postgresql://")):
            self.url = self.url.replace("postgres://", "postgresql://", 1)
            self.kind = "postgresql"
        else:
            self.kind = "sqlite"
            if self.url and self.url.startswith("sqlite:///"):
                self.path = self.url[len("sqlite:///"):]
            else:
                self.path = DEFAULT_SQLITE
            if self.path != ":memory:":
                os.makedirs(os.path.dirname(os.path.abspath(self.path)), exist_ok=True)
        self._create_tables()

    @contextmanager
    def connect(self):
        """Open one transaction, committing on success and rolling back on error."""
        if self.kind == "sqlite":
            conn = sqlite3.connect(self.path)
            conn.execute("PRAGMA foreign_keys = ON")
        else:
            conn = psycopg.connect(self.url)
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

    def _q(self, sql):
        return sql.replace("?", "%s") if self.kind == "postgresql" else sql

    @staticmethod
    def _period_key(start, end):
        if start is None and end is None:
            return "default"
        return f"{start.isoformat()}|{end.isoformat()}"

    def _create_tables(self):
        pk = "SERIAL PRIMARY KEY" if self.kind == "postgresql" else "INTEGER PRIMARY KEY AUTOINCREMENT"
        statements = [
            f"""CREATE TABLE IF NOT EXISTS users (
                id {pk}, name VARCHAR(60) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL, created_at VARCHAR(32) NOT NULL DEFAULT '')""",
            """CREATE TABLE IF NOT EXISTS plans (
                user_id INTEGER PRIMARY KEY REFERENCES users(id),
                income BIGINT NOT NULL DEFAULT 0 CHECK (income >= 0),
                start_date VARCHAR(10), end_date VARCHAR(10), updated_at VARCHAR(32) NOT NULL)""",
            f"""CREATE TABLE IF NOT EXISTS plan_items (
                id {pk}, user_id INTEGER NOT NULL REFERENCES users(id),
                uid VARCHAR(40) NOT NULL,
                category VARCHAR(10) NOT NULL CHECK (category IN ('needs','wants','savings')),
                name VARCHAR(60) NOT NULL, budget BIGINT NOT NULL CHECK (budget >= 0),
                sort_order INTEGER NOT NULL, UNIQUE (user_id, uid))""",
            "CREATE INDEX IF NOT EXISTS idx_items_user ON plan_items (user_id)",
            f"""CREATE TABLE IF NOT EXISTS item_log (
                id {pk}, item_id INTEGER NOT NULL REFERENCES plan_items(id),
                day VARCHAR(10) NOT NULL, amount BIGINT NOT NULL)""",
            "CREATE INDEX IF NOT EXISTS idx_log_item ON item_log (item_id)",
            """CREATE TABLE IF NOT EXISTS budget_periods (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                period_key VARCHAR(24) NOT NULL, income BIGINT NOT NULL DEFAULT 0 CHECK (income >= 0),
                start_date VARCHAR(10), end_date VARCHAR(10), updated_at VARCHAR(32) NOT NULL,
                UNIQUE (user_id, period_key))""",
            """CREATE TABLE IF NOT EXISTS period_items (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                period_id INTEGER NOT NULL REFERENCES budget_periods(id) ON DELETE CASCADE,
                uid VARCHAR(40) NOT NULL,
                category VARCHAR(10) NOT NULL CHECK (category IN ('needs','wants','savings')),
                name VARCHAR(60) NOT NULL, budget BIGINT NOT NULL CHECK (budget >= 0),
                sort_order INTEGER NOT NULL, UNIQUE (period_id, uid))""",
            "CREATE INDEX IF NOT EXISTS idx_period_items_period ON period_items (period_id)",
            """CREATE TABLE IF NOT EXISTS period_item_log (
                id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                item_id INTEGER NOT NULL REFERENCES period_items(id) ON DELETE CASCADE,
                day VARCHAR(10) NOT NULL, amount BIGINT NOT NULL)""",
            "CREATE INDEX IF NOT EXISTS idx_period_log_item ON period_item_log (item_id)",
            """CREATE TABLE IF NOT EXISTS period_migrations (
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                period_key VARCHAR(24) NOT NULL, PRIMARY KEY (user_id, period_key))""",
        ]
        if self.kind == "sqlite":
            statements[6] = statements[6].replace(
                "INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY",
                "INTEGER PRIMARY KEY AUTOINCREMENT",
            )
            statements[7] = statements[7].replace(
                "INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY",
                "INTEGER PRIMARY KEY AUTOINCREMENT",
            )
            statements[9] = statements[9].replace(
                "INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY",
                "INTEGER PRIMARY KEY AUTOINCREMENT",
            )
        with self.connect() as conn:
            cur = conn.cursor()
            for statement in statements:
                cur.execute(statement)
            if self.kind == "sqlite":
                columns = [row[1] for row in cur.execute("PRAGMA table_info(users)").fetchall()]
                if "created_at" not in columns:
                    cur.execute("ALTER TABLE users ADD COLUMN created_at VARCHAR(32) NOT NULL DEFAULT ''")
            else:
                cur.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at VARCHAR(32) NOT NULL DEFAULT ''")
            self._migrate_legacy_plans(cur)

    def _migrate_legacy_plans(self, cur):
        cur.execute("SELECT user_id, income, start_date, end_date, updated_at FROM plans")
        for user_id, income, start_value, end_value, updated_at in cur.fetchall():
            try:
                start = date.fromisoformat(start_value) if start_value else None
                end = date.fromisoformat(end_value) if end_value else None
            except ValueError:
                start = end = None
            if (start is None) != (end is None):
                start = end = None
                start_value = end_value = None
            key = self._period_key(start, end)
            cur.execute(self._q(
                "SELECT 1 FROM period_migrations WHERE user_id = ? AND period_key = ?"
            ), (user_id, key))
            if cur.fetchone():
                continue
            cur.execute(self._q(
                "SELECT id FROM budget_periods WHERE user_id = ? AND period_key = ?"
            ), (user_id, key))
            period = cur.fetchone()
            if period:
                period_id = period[0]
            else:
                cur.execute(self._q(
                    "INSERT INTO budget_periods "
                    "(user_id, period_key, income, start_date, end_date, updated_at) "
                    "VALUES (?, ?, ?, ?, ?, ?) RETURNING id"
                ), (user_id, key, income, start_value, end_value, updated_at or _now()))
                period_id = cur.fetchone()[0]
                cur.execute(self._q(
                    "SELECT id, uid, category, name, budget, sort_order FROM plan_items "
                    "WHERE user_id = ? ORDER BY sort_order"
                ), (user_id,))
                for item_id, uid, category, name, budget, order in cur.fetchall():
                    cur.execute(self._q(
                        "INSERT INTO period_items (period_id, uid, category, name, budget, sort_order) "
                        "VALUES (?, ?, ?, ?, ?, ?) RETURNING id"
                    ), (period_id, uid, category, name, budget, order))
                    new_item_id = cur.fetchone()[0]
                    cur.execute(self._q(
                        "INSERT INTO period_item_log (item_id, day, amount) "
                        "SELECT ?, day, amount FROM item_log WHERE item_id = ?"
                    ), (new_item_id, item_id))
            cur.execute(self._q(
                "INSERT INTO period_migrations (user_id, period_key) VALUES (?, ?)"
            ), (user_id, key))

    def describe(self):
        return {"database": self.kind}

    def ping(self):
        with self.connect() as conn:
            conn.cursor().execute("SELECT 1")

    def create_user(self, name, email, password_hash):
        try:
            with self.connect() as conn:
                cur = conn.cursor()
                cur.execute(self._q(
                    "INSERT INTO users (name, email, password_hash, created_at) "
                    "VALUES (?, ?, ?, ?) RETURNING id"
                ), (name, email, password_hash, _now()))
                return cur.fetchone()[0]
        except (sqlite3.IntegrityError, psycopg.IntegrityError) as exc:
            raise DuplicateEmail() from exc

    def _user(self, where, param):
        with self.connect() as conn:
            cur = conn.cursor()
            cur.execute(self._q(
                f"SELECT id, name, email, password_hash FROM users WHERE {where} = ?"
            ), (param,))
            row = cur.fetchone()
        return dict(zip(("id", "name", "email", "password_hash"), row)) if row else None

    def get_user_by_email(self, email):
        return self._user("email", email)

    def get_user(self, uid):
        return self._user("id", uid) if isinstance(uid, int) else None

    def _load_period(self, cur, user_id, start=None, end=None, latest=False):
        if latest:
            cur.execute(self._q(
                "SELECT id, income, start_date, end_date FROM budget_periods "
                "WHERE user_id = ? ORDER BY updated_at DESC, id DESC LIMIT 1"
            ), (user_id,))
        else:
            key = self._period_key(start, end)
            cur.execute(self._q(
                "SELECT id, income, start_date, end_date FROM budget_periods "
                "WHERE user_id = ? AND period_key = ?"
            ), (user_id, key))
        row = cur.fetchone()
        if not row:
            return {
                "income": 0,
                "start": start,
                "end": end,
                "items": [],
            }
        period_id, income, start_value, end_value = row
        cur.execute(self._q(
            "SELECT id, uid, category, name, budget FROM period_items "
            "WHERE period_id = ? ORDER BY sort_order"
        ), (period_id,))
        items = cur.fetchall()
        cur.execute(self._q(
            "SELECT l.item_id, l.day, l.amount FROM period_item_log l "
            "JOIN period_items i ON i.id = l.item_id WHERE i.period_id = ? ORDER BY l.id"
        ), (period_id,))
        logs = {}
        for item_id, day, amount in cur.fetchall():
            logs.setdefault(item_id, []).append((date.fromisoformat(day), amount))
        return {
            "income": income,
            "start": date.fromisoformat(start_value) if start_value else None,
            "end": date.fromisoformat(end_value) if end_value else None,
            "items": [
                {"uid": item[1], "category": item[2], "name": item[3], "budget": item[4],
                 "log": logs.get(item[0], [])}
                for item in items
            ],
        }

    def load_plan(self, user_id, start=None, end=None, latest=None):
        if latest is None:
            latest = start is None and end is None
        with self.connect() as conn:
            return self._load_period(conn.cursor(), user_id, start, end, latest)

    def save_plan(self, user_id, norm):
        start = norm["start"].isoformat() if norm["start"] else None
        end = norm["end"].isoformat() if norm["end"] else None
        key = self._period_key(norm["start"], norm["end"])
        with self.connect() as conn:
            cur = conn.cursor()
            cur.execute(self._q(
                "INSERT INTO budget_periods "
                "(user_id, period_key, income, start_date, end_date, updated_at) "
                "VALUES (?, ?, ?, ?, ?, ?) "
                "ON CONFLICT (user_id, period_key) DO UPDATE SET "
                "income = excluded.income, start_date = excluded.start_date, "
                "end_date = excluded.end_date, updated_at = excluded.updated_at "
                "RETURNING id"
            ), (user_id, key, norm["income"], start, end, _now()))
            period_id = cur.fetchone()[0]
            cur.execute(self._q(
                "DELETE FROM period_item_log WHERE item_id IN "
                "(SELECT id FROM period_items WHERE period_id = ?)"
            ), (period_id,))
            cur.execute(self._q("DELETE FROM period_items WHERE period_id = ?"), (period_id,))
            for pos, item in enumerate(norm["items"]):
                cur.execute(self._q(
                    "INSERT INTO period_items (period_id, uid, category, name, budget, sort_order) "
                    "VALUES (?, ?, ?, ?, ?, ?) RETURNING id"
                ), (period_id, item["uid"], item["category"], item["name"], item["budget"], pos))
                item_id = cur.fetchone()[0]
                if item["log"]:
                    cur.executemany(self._q(
                        "INSERT INTO period_item_log (item_id, day, amount) VALUES (?, ?, ?)"
                    ), [(item_id, day.isoformat(), amount) for day, amount in item["log"]])

    def delete_period(self, user_id, start, end):
        key = self._period_key(start, end)
        with self.connect() as conn:
            cur = conn.cursor()
            cur.execute(self._q(
                "DELETE FROM budget_periods WHERE user_id = ? AND period_key = ?"
            ), (user_id, key))
            return cur.rowcount > 0
